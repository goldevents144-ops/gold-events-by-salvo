/**
 * Deep-merge two dictionaries. `base` is canonical (full), `override` is partial.
 * Functions are taken from whichever side defines them (functions like
 * `contactServicesSelected`).
 */
function deepMerge<T>(base: T, override: unknown): T {
  if (typeof base === "function") return base;
  if (typeof override === "function") return override as T;
  if (Array.isArray(base)) return (override ?? base) as T;
  if (base && typeof base === "object") {
    const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
    const ov = (override ?? {}) as Record<string, unknown>;
    for (const key of Object.keys(out)) {
      if (key in ov) {
        out[key] = deepMerge(out[key], ov[key]);
      }
    }
    return out as T;
  }
  // primitive
  return (override === undefined ? base : (override as T));
}

/**
 * Returns the resolved dictionary for a language: Italian merged with
 * whatever overrides exist for the requested language. Always returns a
 * complete Dictionary (every key present), falling back to IT for missing keys.
 */
export function getDictionary(lang: Lang): Dictionary {
  const base = dictionaries[DEFAULT_LANG] as Dictionary;
  const ov = dictionaries[lang] as PartialDict | undefined;
  if (!ov || lang === DEFAULT_LANG) return base;
  return deepMerge(base, ov) as Dictionary;
}

/** Convenience: resolved dictionary for the active UI lang (used by client store). */
export type ResolvedDictionary = ReturnType<typeof getDictionary>;
